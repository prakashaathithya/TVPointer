package com.tvpointer.app

/** HID report descriptor and US keyboard map for a combo keyboard + mouse + media keys. */
object HidReports {
    const val ID_KEYBOARD = 1
    const val ID_MOUSE = 2
    const val ID_CONSUMER = 3

    const val KEYBOARD_SIZE = 8 // modifiers, reserved, 6 keys
    const val MOUSE_SIZE = 5    // buttons, x, y, wheel, horizontal pan
    const val CONSUMER_SIZE = 2 // 16-bit usage

    const val MOD_SHIFT = 0x02
    const val KEY_ENTER = 0x28
    const val KEY_BACKSPACE = 0x2A

    // Keyboard arrow keys; Android TV treats these as D-pad Up/Down/Left/Right.
    const val KEY_RIGHT = 0x4F
    const val KEY_LEFT = 0x50
    const val KEY_DOWN = 0x51
    const val KEY_UP = 0x52

    const val USAGE_MUTE = 0x00E2
    const val USAGE_VOLUME_UP = 0x00E9
    const val USAGE_VOLUME_DOWN = 0x00EA
    const val USAGE_AC_HOME = 0x0223
    const val USAGE_AC_BACK = 0x0224

    val DESCRIPTOR: ByteArray = intArrayOf(
        // ---- Keyboard (report 1)
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, ID_KEYBOARD,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,             // modifier bits
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,             // reserved byte
        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
        0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, // 6 key slots
        0xC0,
        // ---- Mouse (report 2)
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, ID_MOUSE,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x95, 0x03, 0x75, 0x01, 0x81, 0x02,             // 3 buttons
        0x95, 0x01, 0x75, 0x05, 0x81, 0x01,             // padding
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, // x, y, wheel
        0x05, 0x0C, 0x0A, 0x38, 0x02,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06, // horizontal pan
        0xC0, 0xC0,
        // ---- Consumer control (report 3): Home, Back
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, ID_CONSUMER,
        0x15, 0x00, 0x26, 0xFF, 0x03, 0x19, 0x00, 0x2A, 0xFF, 0x03,
        0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
        0xC0,
    ).map { it.toByte() }.toByteArray()

    /** HID usage and whether Shift is needed, for a US keyboard layout. Null if not typeable. */
    fun keyFor(c: Char): Pair<Int, Boolean>? = when (c) {
        in 'a'..'z' -> (0x04 + (c - 'a')) to false
        in 'A'..'Z' -> (0x04 + (c - 'A')) to true
        in '1'..'9' -> (0x1E + (c - '1')) to false
        '0' -> 0x27 to false
        '\n' -> KEY_ENTER to false
        '\t' -> 0x2B to false
        ' ' -> 0x2C to false
        else -> SYMBOLS[c]
    }

    private val SYMBOLS: Map<Char, Pair<Int, Boolean>> = buildMap {
        fun plain(c: Char, k: Int) = put(c, k to false)
        fun shift(c: Char, k: Int) = put(c, k to true)
        "!@#$%^&*()".forEachIndexed { i, c -> shift(c, if (i == 9) 0x27 else 0x1E + i) }
        plain('-', 0x2D); shift('_', 0x2D)
        plain('=', 0x2E); shift('+', 0x2E)
        plain('[', 0x2F); shift('{', 0x2F)
        plain(']', 0x30); shift('}', 0x30)
        plain('\\', 0x31); shift('|', 0x31)
        plain(';', 0x33); shift(':', 0x33)
        plain('\'', 0x34); shift('"', 0x34)
        plain('`', 0x35); shift('~', 0x35)
        plain(',', 0x36); shift('<', 0x36)
        plain('.', 0x37); shift('>', 0x37)
        plain('/', 0x38); shift('?', 0x38)
        // Smart punctuation from phone keyboards -> plain ASCII
        shift('“', 0x34); shift('”', 0x34); plain('‘', 0x34); plain('’', 0x34)
    }
}
